import {state,saveListeningProgress} from './storage.js';
import {LISTENING_MODULES,LISTENING_LEVELS,LISTENING_COUNT,
  listeningModule,listeningStats,buildListeningSession,gradeListeningAnswer,
  finishListeningSession} from './listening-model.js';

const element=(tag,className='',content=null)=>{
  const node=document.createElement(tag);
  if(className) node.className=className;
  if(content!==null) node.textContent=content;
  return node;
};
const button=(text,cls,action)=>{
  const node=element('button',cls,text);
  node.type='button';
  node.addEventListener('click',action);
  return node;
};
function line(parent,cls,text){parent.append(element('p',cls,text));}

export function initListening({getCards,playAudio,stopAudio,canPlayAudio}) {
  const root=document.getElementById('listeningRoot');
  const view=document.getElementById('listeningView');
  if(!root || !view) return {route(){},refresh(){}};
  let moduleId=null;
  let levelId='everyday';
  let questions=null;
  let index=0;
  let selected=null;
  let confirmed=false;
  let completed=false;
  let answers=[];
  let audioWarning='';

  const resetSession=()=>{
    stopAudio();
    questions=null;index=0;selected=null;confirmed=false;completed=false;answers=[];audioWarning='';
  };
  function chooseModule(id){
    if(!listeningModule(id))return;
    location.hash='listen/'+id;
  }
  function startSession() {
    if(!moduleId) return;
    try {
      questions=buildListeningSession(getCards(),moduleId,levelId,state.listeningProgress);
      index=0;selected=null;confirmed=false;completed=false;answers=[];
      audioWarning='';
    } catch(error) {
      questions=null;
      audioWarning=getCards().length ? error.message : 'Waiting for the HSK sentence bank…';
    }
    render();
  }
  function navigateHome() {location.hash='review';}
  function dashboard() {
    const back=button('← Practice','review-small-button review-back',navigateHome);
    root.append(back);
    const intro=element('div','review-home-intro');
    intro.append(element('p','review-kicker','PRACTICE · LISTENING'));
    intro.append(element('h1','', 'Listening Trainer'));
    line(intro,'','Five short questions per session. Listen to a Mandarin sentence, choose its meaning, then see the Chinese characters and pinyin.');
    root.append(intro);

    const picker=element('div','listen-level');
    picker.append(element('span','listen-label','Session difficulty'));
    const choices=element('div','listen-level-choices');
    for(const level of LISTENING_LEVELS) {
      const control=button(level.title,'listen-level-button'+(level.id===levelId?' is-selected':''),()=>{
        levelId=level.id;render();
      });
      control.setAttribute('aria-pressed',String(level.id===levelId));
      choices.append(control);
    }
    picker.append(choices);
    root.append(picker);

    const grid=element('div','review-chapter-grid');
    for(const module of LISTENING_MODULES) {
      const stats=listeningStats(state.listeningProgress,module.id);
      const item=button('','review-chapter-card listen-module',()=>chooseModule(module.id));
      item.setAttribute('aria-label','Start '+module.title+' listening session');
      item.append(element('span','review-chapter-num','5 QUESTIONS · '+module.chapters.length+' CHAPTER'+(module.chapters.length===1?'':'S')));
      item.append(element('span','review-chapter-name',module.title));
      item.append(element('span','listen-module-summary',module.summary));
      item.append(element('span','review-chapter-meta',
        stats.attempts ? 'Best '+stats.best+'% · '+stats.attempts+' sessions' : 'Not started'));
      grid.append(item);
    }
    root.append(grid);
    line(root,'listen-footnote','Audio is generated by the Mandarin speech voice installed in your browser. Listening works after an initial online load when offline speech voices are available.');
  }
  function audioButtons(panel,question) {
    const row=element('div','listen-audio-controls');
    const hear=(rate)=>{
      if(!canPlayAudio){audioWarning='This browser does not support speech playback. Reveal and skip this question.';render();return;}
      try {
        const result=playAudio(question.zh,rate);
        if(result===false) {audioWarning='Could not play Mandarin audio. Try your device speech settings.';render();}
        else if(audioWarning){audioWarning='';render();}
      }catch{
        audioWarning='Could not play Mandarin audio. Try your device speech settings.';
        render();
      }
    };
    const play=button('▶ Listen','listen-play',()=>hear(0.85));
    const slow=button('↺ Slower','listen-slow',()=>hear(0.65));
    play.disabled=!canPlayAudio;slow.disabled=!canPlayAudio;
    row.append(play,slow);
    panel.append(row);
    if(audioWarning) line(panel,'listen-audio-note listen-warning',audioWarning);
    else line(panel,'listen-audio-note','Tap Listen to hear the sentence. Slow replay is available.');
  }
  function questionView() {
    const question=questions[index];
    const module=listeningModule(moduleId);
    root.append(button('← Listening topics','review-small-button review-back',()=>{
      resetSession();location.hash='listen';
    }));
    const heading=element('div','listen-question-heading');
    heading.append(element('p','review-kicker',module.title.toUpperCase()+' · '+levelId.toUpperCase()));
    heading.append(element('h1','', 'What did you hear?'));
    line(heading,'review-description','Choose the English meaning of the spoken Mandarin sentence.');
    root.append(heading);
    const counter=element('div','listen-count');
    counter.append(element('strong','', 'Question '+(index+1)+' of '+questions.length));
    const track=element('div','review-progress-track');
    const bar=element('span','review-progress-fill');
    bar.style.width=((index+(confirmed?1:0))/questions.length*100)+'%';
    track.append(bar);counter.append(track);
    root.append(counter);
    const panel=element('section','review-panel listen-question');
    const hidden=element('div','listen-hidden-transcript');
    hidden.append(element('span','','♫'));
    line(hidden,'','The Chinese sentence is hidden until you answer.');
    panel.append(hidden);
    audioButtons(panel,question);
    const choices=element('div','listen-options');
    for(let i=0;i<question.choices.length;i++){
      const label=String.fromCharCode(65+i)+'. '+question.choices[i];
      const option=button(label,'listen-choice'+(selected===i?' is-selected':'')+
        (confirmed&&i===question.correctIndex?' is-correct':'')+
        (confirmed&&i===selected&&selected!==question.correctIndex?' is-wrong':''),()=>{
          if(confirmed)return;
          selected=i;
          render();
        });
      option.setAttribute('aria-pressed',String(selected===i));
      option.disabled=confirmed;
      choices.append(option);
    }
    panel.append(choices);
    if(!confirmed){
      const submit=button('Check answer','review-action listen-submit',()=>{
        if(selected===null)return;
        answers[index]=selected;
        confirmed=true;
        stopAudio();
        render();
      });
      submit.disabled=selected===null;
      panel.append(submit);
      panel.append(button('Cannot hear? Reveal and skip','listen-skip',()=>{
        answers[index]=null;
        selected=null;
        confirmed=true;
        stopAudio();
        render();
      }));
    } else {
      const correct=gradeListeningAnswer(question,answers[index]);
      const feedback=element('div','listen-feedback '+(correct?'is-correct':'is-missed'));
      feedback.setAttribute('role','status');
      feedback.append(element('strong','',answers[index]===null?'Skipped':correct?'Correct':'Not quite'));
      line(feedback,'','Correct meaning: '+question.en);
      panel.append(feedback);
      const transcript=element('div','listen-transcript');
      transcript.append(element('p','review-section-label','CHINESE TRANSCRIPT'));
      const zh=element('div','listen-chinese',question.zh);zh.lang='zh-Hans';
      transcript.append(zh);
      transcript.append(element('div','listen-pinyin',question.py));
      transcript.append(element('div','listen-translation',question.en));
      transcript.append(element('p','review-section-label listen-breakdown-heading','WORD BY WORD'));
      for(const part of question.breakdown){
        const piece=element('div','listen-breakdown');
        piece.append(element('strong','',part.zh),element('span','',part.py),element('span','',part.en));
        transcript.append(piece);
      }
      panel.append(transcript);
      panel.append(button(index===questions.length-1?'See results':'Next sentence →','review-action listen-submit',()=>{
        stopAudio();
        index++;
        selected=null;
        confirmed=false;
        audioWarning='';
        if(index>=questions.length){
          completed=true;
          state.listeningProgress=finishListeningSession(state.listeningProgress,moduleId,questions,answers);
          saveListeningProgress();
        }
        render();
      }));
    }
    root.append(panel);
  }
  function resultsView() {
    root.append(button('← Listening topics','review-small-button review-back',()=>{
      resetSession();location.hash='listen';
    }));
    const current=listeningStats(state.listeningProgress,moduleId);
    const count=questions.filter((q,i)=>gradeListeningAnswer(q,answers[i])).length;
    const box=element('section','review-panel listen-results');
    box.append(element('p','review-kicker','SESSION COMPLETE'));
    box.append(element('h1','',count+' / '+questions.length+' correct'));
    line(box,'review-description','Score: '+Math.round(count/questions.length*100)+'% · Personal best: '+current.best+'%');
    line(box,'review-note','You have completed '+current.attempts+' listening session'+(current.attempts===1?'':'s')+' in this topic.');
    const missed=questions.filter((question,i)=>!gradeListeningAnswer(question,answers[i]));
    if(missed.length){
      box.append(element('h2','listen-missed-heading','Review these sentences'));
      for(const q of missed){
        const item=element('div','listen-missed');
        const cn=element('strong','',q.zh);cn.lang='zh-Hans';item.append(cn);
        item.append(element('div','listen-pinyin',q.py),element('div','listen-translation',q.en));
        box.append(item);
      }
    }
    box.append(button('Practice five more →','review-action listen-submit',()=>{
      resetSession();startSession();
    }));
    box.append(button('Choose another topic','review-small-button listen-all-topics',()=>{
      resetSession();location.hash='listen';
    }));
    root.append(box);
  }
  function render() {
    if(view.hidden)return;
    root.replaceChildren();
    if(!moduleId){dashboard();return;}
    if(!questions){
      root.append(button('← Listening topics','review-small-button review-back',()=>{location.hash='listen';}));
      const intro=element('section','review-panel');
      intro.append(element('h2','',listeningModule(moduleId).title));
      line(intro,'review-description',audioWarning || 'Loading HSK sentence cards…');
      if(getCards().length) intro.append(button('Start session','review-action',startSession));
      root.append(intro);
      return;
    }
    if(completed)resultsView();
    else questionView();
  }
  function route() {
    const match=/^#listen(?:\/([a-z-]+))?$/.exec(location.hash);
    if(!match){stopAudio();return;}
    const target=match[1] || null;
    if(target && !listeningModule(target)) {
      location.hash='listen';return;
    }
    if(moduleId!==target){resetSession();moduleId=target;}
    if(moduleId && !questions && getCards().length) startSession();
    else render();
  }
  return {route,refresh(){if(!view.hidden)route();}};
}
